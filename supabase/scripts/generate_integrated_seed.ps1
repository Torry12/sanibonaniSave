$ErrorActionPreference = 'Stop'

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$repoRoot = (Get-Item $scriptDir).Parent.Parent.FullName
$seedFiles = @(
    'MASTER_SEED_DATA.sql',
    '11_SEED_TEST_DATA_10_GROUPS_100_MEMBERS.sql',
    '15_SEED_LIVE_PAYOUT_REQUESTS.sql',
    '16_SEED_50_PAYMENT_REQUESTS_AND_APPROVALS.sql',
    '17_SEED_PLATFORM_FINANCIAL_ESCALATIONS.sql',
    '19_SEED_BURIAL_CLAIM_ESCALATIONS.sql',
    '31_REAL_LIFE_INTEGRITY_SEEDS.sql',
    '20_SEED_12_MONTHS_TRANSACTIONS.sql',
    '21_SEED_VALID_BURIAL_CLAIMS.sql'
)

$outputPath = Join-Path $repoRoot 'supabase\SEED_ALL_DATA.sql'
$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('-- SanibonaniSave integrated seed entry point; generated by scripts/generate_integrated_seed.ps1')
[void]$builder.AppendLine('-- Test identities use reserved seed domains; records are scoped to LIGHT-/SEED-/SIM-FLOWS- groups.')
[void]$builder.AppendLine('-- Financial-drift records are deliberate audit fixtures, limited to the LIGHT-Stokvel test group.')
[void]$builder.AppendLine('BEGIN;')

foreach ($file in $seedFiles) {
    $path = Join-Path $repoRoot "supabase\$file"
    if (-not (Test-Path -LiteralPath $path)) { throw "Required seed source missing: $path" }
    [void]$builder.AppendLine("`n-- =====================================================================")
    [void]$builder.AppendLine("-- Integrated source: $file")
    [void]$builder.AppendLine("-- =====================================================================")
    [void]$builder.Append((Get-Content -LiteralPath $path -Raw))
    [void]$builder.AppendLine()
}

[void]$builder.AppendLine('COMMIT;')
[System.IO.File]::WriteAllText($outputPath, $builder.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated $outputPath from $($seedFiles.Count) seed modules."
