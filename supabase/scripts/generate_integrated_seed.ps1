<#
generate_integrated_seed.ps1

Rebuilds supabase\SEED_ALL_DATA.sql: one transactional, paste-able seed script that inlines
every seed master in the order listed below. This is the manual "seed a clean local tier in
one paste" entry point; supabase\00_REBUILD_ALL.sql applies the same modules through \i.

Deterministic by design: masters in, verbatim module bodies out, so re-running this script
with unchanged masters produces a byte-identical file.

Usage (from repo root):
  powershell -ExecutionPolicy Bypass -File .\supabase\scripts\generate_integrated_seed.ps1

Output:
  supabase\SEED_ALL_DATA.sql

Encoding note: the masters are UTF-8 with CRLF endings, so they are read with an explicit
UTF-8 encoding. A default-encoding Get-Content decoded those comment rules as ANSI and
re-emitted them as mojibake, while AppendLine mixed LF into the file - that is how the
previous SEED_ALL_DATA.sql was corrupted. Line endings are normalised on write.

Dev fixtures only. A cloud project must never be seeded from here; see
supabase/online/00_REBUILD_ONLINE.sql, which includes no SEED_*.sql at all.
#>

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$repoRoot  = (Get-Item $scriptDir).Parent.Parent.FullName
$sb        = Join-Path $repoRoot 'supabase'
$dst       = Join-Path $sb 'SEED_ALL_DATA.sql'

# 15_SEED_LIVE_PAYOUT_REQUESTS.sql is not in 00_REBUILD_ALL.sql; it stays here because this
# file is the one-paste seed for a freshly reset local tier.
$seedFiles = @(
    '10_SEED_HELPERS.sql',
    'MASTER_SEED_DATA.sql',
    '11_SEED_TEST_DATA_10_GROUPS_100_MEMBERS.sql',
    '15_SEED_LIVE_PAYOUT_REQUESTS.sql',
    '16_SEED_50_PAYMENT_REQUESTS_AND_APPROVALS.sql',
    '17_SEED_PLATFORM_FINANCIAL_ESCALATIONS.sql',
    '19_SEED_BURIAL_CLAIM_ESCALATIONS.sql',
    '31_REAL_LIFE_INTEGRITY_SEEDS.sql',
    '20_SEED_12_MONTHS_TRANSACTIONS.sql',
    '21_SEED_VALID_BURIAL_CLAIMS.sql',
    '90_SEED_INTEGRITY_GATE.sql'
)

$utf8 = New-Object System.Text.UTF8Encoding($false)
$sep  = '-- ' + ('=' * 69)
$nl   = "`n"

$preamble = @(
    '-- SanibonaniSave integrated seed entry point; generated by scripts/generate_integrated_seed.ps1',
    '-- Test identities use reserved seed domains; records are scoped to LIGHT-/SEED-/SIM-FLOWS- groups.',
    '-- Scenario 4 injects a balance drift and repairs it immediately: every group ends ledger-consistent.',
    '-- The last module is 90_SEED_INTEGRITY_GATE.sql, inside this transaction: a failed check rolls the seed back.',
    'BEGIN;'
) -join $nl

# Built with an explicit accumulator: a @(foreach ...) would capture any Write-Output from
# inside the loop and splice it into the SQL.
$blocks = @()
foreach ($file in $seedFiles) {
    $p = Join-Path $sb $file
    if (-not (Test-Path -LiteralPath $p)) { throw "Required seed source missing: $p" }
    $body = [System.IO.File]::ReadAllText($p, $utf8).Replace("`r`n", "`n").TrimEnd("`n")
    if ([string]::IsNullOrWhiteSpace($body)) { throw "Required seed source is empty: $p" }
    $blocks += (@($sep, "-- Integrated source: $file", $sep, $body) -join $nl)
    Write-Host ("inlined {0,-50} {1,5} lines" -f $file, ($body -split "`n").Count)
}

$text = (@($preamble) + $blocks + @('COMMIT;')) -join ($nl + $nl)
$text = ($text -replace "`r`n", "`n").TrimEnd("`n") + "`n"
$text = $text.Replace("`n", "`r`n")
[System.IO.File]::WriteAllText($dst, $text, $utf8)

Write-Output "Generated $dst from $($seedFiles.Count) seed modules."
